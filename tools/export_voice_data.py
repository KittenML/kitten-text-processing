"""Build fixed voice-profile tables from the frozen ICU 78.2 / CLDR 48 data.

This is build tooling only. The generated C++ data is shared by both engines.
"""
import json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'kitten_text_processing/data/voice/icu78-profiles.json').read_text())
# Language-specific lexical glue; number morphology comes from frozen RBNF.
words={
'en':['point','minus','plus','percent','and','hour','hours','minute','minutes','second','seconds','cent','cents'],
'ar':['فاصلة','سالب','موجب','بالمئة','و','ساعة','ساعات','دقيقة','دقائق','ثانية','ثوان','سنت','سنتات'],
'zh':['点','负','正','百分之','和','时','时','分','分','秒','秒','分','分'],
'nl':['komma','min','plus','procent','en','uur','uur','minuut','minuten','seconde','seconden','cent','cent'],
'fr':['virgule','moins','plus','pour cent','et','heure','heures','minute','minutes','seconde','secondes','centime','centimes'],
'de':['Komma','minus','plus','Prozent','und','Stunde','Stunden','Minute','Minuten','Sekunde','Sekunden','Cent','Cent'],
'hi':['दशमलव','ऋण','धन','प्रतिशत','और','बजे','बजे','मिनट','मिनट','सेकंड','सेकंड','सेंट','सेंट'],
'id':['koma','minus','plus','persen','dan','jam','jam','menit','menit','detik','detik','sen','sen'],
'it':['virgola','meno','più','per cento','e','ora','ore','minuto','minuti','secondo','secondi','centesimo','centesimi'],
'ja':['点','マイナス','プラス','パーセント','と','時','時','分','分','秒','秒','セント','セント'],
'ko':['점','마이너스','플러스','퍼센트','그리고','시','시','분','분','초','초','센트','센트'],
'pl':['przecinek','minus','plus','procent','i','godzina','godzin','minuta','minut','sekunda','sekund','cent','centów'],
'pt':['vírgula','menos','mais','por cento','e','hora','horas','minuto','minutos','segundo','segundos','centavo','centavos'],
'ru':['запятая','минус','плюс','процентов','и','час','часов','минута','минут','секунда','секунд','цент','центов'],
'es':['coma','menos','más','por ciento','y','hora','horas','minuto','minutos','segundo','segundos','centavo','centavos'],
'tr':['virgül','eksi','artı','yüzde','ve','saat','saat','dakika','dakika','saniye','saniye','sent','sent'],
}
def raw(s):
    assert ')KT_DATA"' not in s
    return 'R"KT_DATA('+s+')KT_DATA"'
def arr(xs):return '{'+','.join(raw(x) for x in xs)+'}'
lines=['// Generated by tools/export_voice_data.py. ICU 78.2 / CLDR 48.','// Unicode data: Unicode-3.0 license; see cpp/voice/NOTICE.','#pragma once','#include <string>','#include <vector>','#include <map>','#include <array>','namespace kitten_voice {','struct Currency { std::array<std::string,5> names; int digits; };','struct Profile { std::string language, locale, rules; std::vector<std::string> rule_names, months, months_short, words; std::map<std::string,Currency> currencies; bool decimal_comma; };','inline const std::vector<Profile>& profiles() { static const std::vector<Profile> p = {']
for lang,p in data.items():
    currencies='{'+','.join('{'+raw(c)+', Currency{'+arr([v[k] for k in ('one','two','few','many','other')])+','+str(v['digits'])+'}}' for c,v in p['currencies'].items())+'}'
    fields=[raw(lang),raw(p['locale']),raw(p['rules']),arr(p['rule_names']),arr(p['months']),arr(p['months_short']),arr(words[lang]),currencies,str(lang in {'nl','fr','de','id','it','pl','pt','ru','es','tr'}).lower()]
    lines.append('Profile{'+','.join(fields)+'},')
lines+=['}; return p; }','}  // namespace kitten_voice']
(ROOT/'cpp/voice/voice_data.hpp').write_text('\n'.join(lines)+'\n')
